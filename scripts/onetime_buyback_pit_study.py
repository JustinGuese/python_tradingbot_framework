"""Buyback 8-K drift restricted to point-in-time S&P 500 members (2026-11-18).

The S&P 100 buyback result (event-buyback-2026-11.md, 10d t 1.8-2.6) used TODAY's S&P 100 list. If some of that edge is
survivorship (names that grew into the index), it should sit in events dated BEFORE the name was an S&P 500 member and
vanish in events where the name was already a member at the announcement (`sp500_members(event_date)`).

PRE-REGISTERED (before any result was read): one primary test, hold 10 sessions, 10 bp/side, events from all cached
buyback filings (sp100/sp400/sp600 groups, 2010+, 30-day dedupe) whose symbol was in the S&P 500 on the acceptance
date. Descriptive: holds {5,10,20}, the complement (not a member at event), and sp100-group split by membership.
Limits: no delisted names (the cache only has today's S&P 100/400/600), so names removed from the index for failing are
still missing; this only removes the grew-into-the-index events.

Usage: POSTGRES_URI=x:y@127.0.0.1:1/z PYTHONPATH=. .venv/bin/python scripts/onetime_buyback_pit_study.py
"""

from __future__ import annotations

import pickle
from pathlib import Path

import pandas as pd

import scripts.event_book_lib as lib
from tradingbot.utils.universes import sp500_members

OUT = "docs/backtests/buyback-pit-2026-11.md"
HOLDS = (5, 10, 20)


def main() -> int:
    meta = pickle.loads((lib.BROAD_DIR / "candidates.pkl").read_bytes())
    uni: dict[str, str] = meta["universe"]
    matched = pickle.loads((lib.BROAD_DIR / "events_buyback_raw.pkl").read_bytes())
    sp100 = pickle.loads((lib.BROAD_DIR / "events_buyback_sp100.pkl").read_bytes())
    matched = [m for m in matched if uni.get(m["symbol"]) != "sp100"] + sp100
    raw = pd.DataFrame(matched)
    raw["acceptance_dt"] = pd.to_datetime(raw["acceptance_dt"], utc=True)
    events = lib.dedupe(raw, 30)
    events["grp"] = events["symbol"].map(uni)

    prices = lib.load_prices(sorted(uni))
    syms, idx, R, q = lib.build_matrix(prices)
    col = {s: i for i, s in enumerate(syms)}
    events = events[events["symbol"].isin(col)].reset_index(drop=True)
    events["entry"] = lib.entry_positions(idx, events["acceptance_dt"])
    events = events[events["entry"] < len(idx) - 2].reset_index(drop=True)
    events["sidx"] = events["symbol"].map(col)
    lo = int(events["entry"].min())

    cache: dict[str, set[str]] = {}

    def member(sym: str, dt: pd.Timestamp) -> bool:
        key = dt.strftime("%Y-%m")
        if key not in cache:
            cache[key] = set(sp500_members(dt.strftime("%Y-%m-%d")))
        return sym in cache[key]

    events["pit"] = [member(s, d) for s, d in zip(events["symbol"], events["acceptance_dt"], strict=True)]
    print(events.groupby(["grp", "pit"]).size().to_string())

    sets = {
        "all PIT S&P 500 members at event": events["pit"],
        "NOT a member at event (grew into / never in S&P 500)": ~events["pit"],
        "sp100 list, member at event": (events["grp"] == "sp100") & events["pit"],
        "sp100 list, NOT member at event": (events["grp"] == "sp100") & ~events["pit"],
        "sp100 list, all (reference)": events["grp"] == "sp100",
    }
    rows, res_by = [], {}
    for name, mask in sets.items():
        sub = events[mask]
        for h in HOLDS:
            if len(sub) < 20:
                rows.append(f"| {name} | {h}d | {len(sub)} | too few | | | | | |")
                continue
            e = sub["entry"].to_numpy(dtype=int)
            s = sub["sidx"].to_numpy(dtype=int)
            m = lib.evaluate_book(e, s, h, R, q, 0.001, lo)
            res_by[(name, h)] = m
            rows.append(
                f"| {name}{' (PRIMARY)' if (name, h) == (next(iter(sets)), 10) else ''} | {h}d | {len(sub)} | "
                f"{m['alpha']:+.1f}% | {m['t']:.2f} | {m['beta']:.2f} | {m['a1']:+.1f}% ({m['t1']:.2f}) | "
                f"{m['a2']:+.1f}% ({m['t2']:.2f}) | {'PASS' if lib.passes(m) else 'fail'} |"
            )
            print(rows[-1])

    car = []
    for name, mask in sets.items():
        sub = events[mask]
        for h in HOLDS:
            if len(sub) >= 20:
                car.append(
                    lib.car_row(name, sub["entry"].to_numpy(dtype=int), sub["sidx"].to_numpy(dtype=int), h, R, q, lo)
                )
    prim = res_by.get((next(iter(sets)), 10))
    verdict = "no data" if prim is None else ("pass bar" if lib.passes(prim) else "fail bar")
    text = [
        "# Buyback drift on point-in-time S&P 500 members (generated)",
        "",
        f"**Primary (all PIT members at event, 10 sessions, 10 bp/side): `{verdict}`**. Generated by "
        "`scripts/onetime_buyback_pit_study.py`; pre-registered in its docstring.",
        "",
        f"- Events after dedupe: {len(events)}; PIT members at event: {int(events['pit'].sum())}. Window {idx[lo].date()} to {idx[-1].date()}.",
        "- Universe limit: only today's S&P 100/400/600 have price history here, so delisted/removed names are still missing.",
        "",
        "| Event set | Hold | Events | Alpha/yr | t | Beta | H1 alpha (t) | H2 alpha (t) | Bar |",
        "|---|---|---|---|---|---|---|---|---|",
        *rows,
        "",
        "## Event level",
        "",
        lib.CAR_HEADER,
        *car,
        "",
    ]
    Path(OUT).write_text("\n".join(text), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

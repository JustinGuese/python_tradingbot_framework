"""Prop-Firm Challenge Simulator Study (2026-11).

Evaluates whether buying prop-firm evaluation challenges for candidate trading bot
return streams is positive expected value (EV) after the challenge fee, compared
to a QQQ control and a zero-alpha control at the same leverage.

Candidates:
- C2 blend: 0.39 TARegimeMultiAsset + 0.24 TSMOM + 0.37 GoldenButterfly
  (live weights from values.yaml; see docs/backtests/c2-blend-2026-09.md)
- TSMOM alone
- TARegimeMultiAsset alone

Controls:
- QQQ buy-and-hold at same leverage
- blend minus alpha (same vol and beta as C2 blend, with zero edge)

Presets:
- ftmo_2step_100k
- topstep_50k
- the5ers_hs_100k

Leverage grid: [1, 2, 3, 4, 5, 6]
Walk-forward split: SPLIT = "2023-07-01"
- Best leverage picked by EV on H1 paths only.
- Chosen leverage stats reported on H2 paths.
- Full grid printed for H1 and H2.

Paths:
- Historical paths: horizon=252, step=5
- Block bootstrap: n_paths=5000, block=21, horizon=252, rng=default_rng(7)
"""

import argparse
import logging
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

from scripts.onetime_c2_blend_backtest import _yf, sleeve_returns
from tradingbot.goldenbutterflymombot import GoldenButterflyMomBot
from tradingbot.taregimemultiassetbot import TARegimeMultiAssetBot
from tradingbot.tsmomtrendbot import TSMOMTrendBot
from tradingbot.utils.alpha_report import alpha_stats, load_irx
from tradingbot.utils.prop_challenge import (
    PRESETS,
    block_bootstrap,
    evaluate,
    historical_paths,
    lever,
    verdict,
)
from tradingbot.utils.trial_registry import record_trial

warnings.filterwarnings("ignore")
logging.disable(logging.WARNING)

START = "2019-01-01"
SPLIT = "2023-07-01"
LEVERAGE_GRID = [1, 2, 3, 4, 5, 6]
BOOTSTRAP_N_PATHS = 5000
BOOTSTRAP_BLOCK = 21
HORIZON = 252
HIST_STEP = 5
RNG_SEED = 7

# Live C2 sleeve weights from values.yaml (see docs/backtests/c2-blend-2026-09.md)
C2_WEIGHTS = {
    "TARegimeMultiAsset": 0.39,
    "TSMOM": 0.24,
    "GoldenButterfly": 0.37,
}


def format_pct(val: float | None) -> str:
    """Format fractional return/probability as percentage string."""
    if val is None or not np.isfinite(val):
        return "—"
    return f"{val * 100:.1f}%"


def format_usd(val: float | None) -> str:
    """Format USD value as rounded integer string."""
    if val is None or not np.isfinite(val):
        return "—"
    sign = "-" if val < 0 else ""
    return f"{sign}${abs(val):,.0f}"


def format_days(val: float | None) -> str:
    """Format day count as string."""
    if val is None or not np.isfinite(val):
        return "—"
    return f"{val:.0f}d"


def build_markdown_doc(
    h1_results: dict,
    h2_results: dict,
    chosen: dict,
    n_obs: dict,
    intraday_haircut: float,
    start_date: str,
    end_date: str,
) -> str:
    """Generate Markdown document for docs/backtests/prop-challenge-2026-11.md.

    Contains only computed tables, fixed method descriptions, and verdicts chosen
    by verdict(). No hard-coded conclusions or verdict sentences.
    """
    lines = [
        "# Prop-Firm Challenge Simulator Study (2026-11)",
        "",
        "Generated by `scripts/onetime_prop_challenge_study.py --write-doc`.",
        "",
        "## Executive Summary",
        "",
        "This study evaluates whether purchasing prop-firm evaluation challenges for candidate",
        "bot return streams is positive expected value (EV) after the challenge fee, compared",
        "to a QQQ buy-and-hold control and a zero-alpha blend control at the identical leverage.",
        "",
        f"- **Evaluation window:** `{start_date}` to `{end_date}`.",
        f"- **Walk-forward split:** H1 fit (`{start_date}` to `{SPLIT}`) for leverage selection;",
        f"  H2 test (`{SPLIT}` to `{end_date}`) judged out-of-sample.",
        f"- **Intraday haircut:** `--intraday-haircut {intraday_haircut:.2f}` (multiplies negative daily",
        "  returns before breach checks to address intraday drawdown understatement from daily closes).",
        "",
        "### Number of Daily Observations",
        "",
        "| Stream | H1 Observations | H2 Observations | Total Observations |",
        "|---|---|---|---|",
    ]

    for name, counts in n_obs.items():
        lines.append(f"| {name} | {counts['h1']} | {counts['h2']} | {counts['total']} |")

    lines.extend(
        [
            "",
            "## Firm Rule Presets",
            "",
            "| Preset | Target (P1/P2) | Max Loss | Daily Loss | Trailing | Fee | Split | Note |",
            "|---|---|---|---|---|---|---|---|",
        ]
    )

    for key, p in PRESETS.items():
        p1 = p.phases[0]
        p2_target = format_pct(p.phases[1].profit_target) if len(p.phases) > 1 else "—"
        dl = format_pct(p1.daily_loss) if p1.daily_loss is not None else "None"
        lines.append(
            f"| `{key}` | {format_pct(p1.profit_target)} / {p2_target} | "
            f"{format_pct(p1.max_loss)} | {dl} | {p1.trailing} | "
            f"${p.fee:,.0f} | {format_pct(p.profit_split)} | {p.note} |"
        )

    lines.extend(
        [
            "",
            "## Out-of-Sample Results (H2: Chosen Leverage from H1)",
            "",
            "Leverage for each candidate and firm preset was selected solely on H1 by maximizing EV per attempt.",
            "The chosen leverage is evaluated below on out-of-sample H2 paths.",
            "",
            "| Candidate | Preset | Chosen Lev | H2 P(Pass) | H2 P(Breach) | H2 P(Timeout) | H2 EV/Att (Boot) | H2 EV/Att (Hist) | QQQ EV at Lev | Verdict vs QQQ | Verdict vs Zero-Alpha |",
            "|---|---|---|---|---|---|---|---|---|---|---|",
        ]
    )

    for row in chosen["h2_summary"]:
        lines.append(
            f"| {row['candidate']} | `{row['preset']}` | {row['leverage']}x | "
            f"{format_pct(row['cand_boot'].p_pass)} | {format_pct(row['cand_boot'].p_breach)} | "
            f"{format_pct(row['cand_boot'].p_timeout)} | {format_usd(row['cand_boot'].ev_per_attempt)} | "
            f"{format_usd(row['cand_hist'].ev_per_attempt)} | {format_usd(row['qqq_boot'].ev_per_attempt)} | "
            f"`{row['verdict_qqq']}` | `{row['verdict_zero_alpha']}` |"
        )

    lines.extend(
        [
            "",
            "## Full Leverage Grid (H1: Fit / Selection Window)",
            "",
            "Headline metrics computed with 5,000-path circular block bootstrap (block=21, horizon=252).",
            "Historical rolling paths (step=5, horizon=252) shown as consistency check.",
            "",
            "| Candidate / Control | Preset | Lev | P(Pass) Boot | P(Breach) Boot | EV/Att Boot | EV/Att Hist |",
            "|---|---|---|---|---|---|---|",
        ]
    )

    for entry in h1_results:
        b = entry["boot"]
        h = entry["hist"]
        lines.append(
            f"| {entry['stream']} | `{entry['preset']}` | {entry['leverage']}x | "
            f"{format_pct(b.p_pass)} | {format_pct(b.p_breach)} | "
            f"{format_usd(b.ev_per_attempt)} | {format_usd(h.ev_per_attempt)} |"
        )

    lines.extend(
        [
            "",
            "## Full Leverage Grid (H2: Out-of-Sample Window)",
            "",
            "| Candidate / Control | Preset | Lev | P(Pass) Boot | P(Breach) Boot | EV/Att Boot | EV/Att Hist |",
            "|---|---|---|---|---|---|---|",
        ]
    )

    for entry in h2_results:
        b = entry["boot"]
        h = entry["hist"]
        lines.append(
            f"| {entry['stream']} | `{entry['preset']}` | {entry['leverage']}x | "
            f"{format_pct(b.p_pass)} | {format_pct(b.p_breach)} | "
            f"{format_usd(b.ev_per_attempt)} | {format_usd(h.ev_per_attempt)} |"
        )

    lines.extend(
        [
            "",
            "## Methodology & Intraday Caveat",
            "",
            "1. **Paths and Bootstrap:** For each window and leverage level, returns are levered according to",
            "   `lever(r, L, rf, markup) = L * r - L * rf - L * markup / 252`. We simulate paths via circular block",
            "   bootstrap (`n_paths=5000`, `block=21`, `horizon=252`, seed=7) as primary headline, and historical",
            "   rolling paths (`horizon=252`, `step=5`) as robustness check.",
            "2. **Controls:** We evaluate QQQ buy-and-hold at the same leverage, and a synthetic `blend minus alpha`",
            "   control (C2 blend with full-sample alpha/252 subtracted, preserving exact volatility and beta with zero edge).",
            "3. **Intraday Drawdown Caveat:** Daily close returns understate intraday drawdown swings. Breaches of daily-loss",
            "   or trailing limits may occur intraday before a daily close recovers. The `--intraday-haircut` multiplier",
            "   scales negative returns to stress-test breach rates.",
            "4. **Rule Presets:** Presets are approximations assembled from third-party summaries of each firm's",
            "   rules and were not checked against the firms' own terms. Each carries the note",
            "   `VERIFY before buying`. Fees, targets and drawdown types change often.",
            "",
        ]
    )

    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Prop-Firm Challenge Simulator Study")
    parser.add_argument(
        "--write-doc",
        action="store_true",
        help="Write markdown study results to docs/backtests/prop-challenge-2026-11.md",
    )
    parser.add_argument(
        "--intraday-haircut",
        type=float,
        default=1.0,
        help="Multiplier on negative daily returns before breach checks (default: 1.0)",
    )
    args = parser.parse_args()

    print("=" * 80)
    print("PROP-FIRM CHALLENGE SIMULATOR STUDY (2026-11)")
    print("=" * 80)
    print(f"Data start: {START} | Split date: {SPLIT}")
    print(f"Intraday haircut: {args.intraday_haircut:.2f}")

    # 1. Load candidate sleeve returns
    print("\n[1/5] Loading sleeve returns and building candidate streams...")
    r_ta = sleeve_returns(TARegimeMultiAssetBot)
    r_tsmom = sleeve_returns(TSMOMTrendBot)
    r_gb = sleeve_returns(GoldenButterflyMomBot)

    df_sleeves = pd.DataFrame(
        {
            "TARegimeMultiAsset": r_ta,
            "TSMOM": r_tsmom,
            "GoldenButterfly": r_gb,
        }
    ).dropna()
    df_sleeves = df_sleeves[df_sleeves.index >= START]

    # C2 blend from live weights in values.yaml (docs/backtests/c2-blend-2026-09.md)
    r_c2 = (
        C2_WEIGHTS["TARegimeMultiAsset"] * df_sleeves["TARegimeMultiAsset"]
        + C2_WEIGHTS["TSMOM"] * df_sleeves["TSMOM"]
        + C2_WEIGHTS["GoldenButterfly"] * df_sleeves["GoldenButterfly"]
    )
    r_cand_tsmom = df_sleeves["TSMOM"]
    r_cand_ta = df_sleeves["TARegimeMultiAsset"]

    # 2. Load QQQ benchmark and build controls
    print("[2/5] Loading QQQ benchmark and constructing controls...")
    q_raw = _yf(None, "QQQ")
    r_qqq = q_raw.set_index("timestamp")["close"].pct_change().dropna()

    common_idx = df_sleeves.index.intersection(r_qqq.index)
    common_idx = common_idx[common_idx >= START].sort_values()

    r_c2 = r_c2.reindex(common_idx).dropna()
    r_cand_tsmom = r_cand_tsmom.reindex(common_idx).dropna()
    r_cand_ta = r_cand_ta.reindex(common_idx).dropna()
    r_qqq = r_qqq.reindex(common_idx).dropna()

    # Blend minus alpha: residual mean (alpha / 252) subtracted
    astats = alpha_stats(r_c2, r_qqq)
    r_blend_minus_alpha = r_c2 - astats.alpha / 252.0 if astats is not None else r_c2.copy()

    # 3. Risk-free rate
    print("[3/5] Loading risk-free rate (^IRX)...")
    irx = load_irx(START)
    if irx is None or len(irx.dropna()) == 0:
        print("WARNING: load_irx('2019-01-01') returned empty; falling back to 0.04/252")
        rf_daily = pd.Series(0.04 / 252.0, index=common_idx)
    else:
        s = irx.dropna()
        if float(s.mean()) > 0.5:
            s = s / 100.0
        daily_s = s / 252.0
        rf_daily = daily_s.reindex(common_idx).ffill().bfill().fillna(0.04 / 252.0)

    start_date_str = str(common_idx[0].date())
    end_date_str = str(common_idx[-1].date())

    candidates = {
        "C2 blend": r_c2,
        "TSMOM": r_cand_tsmom,
        "TARegimeMultiAsset": r_cand_ta,
    }
    controls = {
        "QQQ": r_qqq,
        "blend minus alpha": r_blend_minus_alpha,
    }
    all_streams = {**candidates, **controls}

    n_obs = {}
    for name, s in all_streams.items():
        s_h1 = s[s.index < SPLIT]
        s_h2 = s[s.index >= SPLIT]
        n_obs[name] = {"h1": len(s_h1), "h2": len(s_h2), "total": len(s)}

    # 4. Run simulations across grid
    print("[4/5] Running simulations across leverage grid [1..6] for H1 and H2...")
    results = {"H1": {}, "H2": {}}
    h1_flat_list = []
    h2_flat_list = []

    for half in ["H1", "H2"]:
        results[half] = {}
        for stream_name, s_series in all_streams.items():
            results[half][stream_name] = {}
            if half == "H1":
                s_half = s_series[s_series.index < SPLIT]
                rf_half = rf_daily[rf_daily.index < SPLIT]
            else:
                s_half = s_series[s_series.index >= SPLIT]
                rf_half = rf_daily[rf_daily.index >= SPLIT]

            r_arr = s_half.to_numpy(dtype=float)
            rf_arr = rf_half.to_numpy(dtype=float)

            for preset_name, preset in PRESETS.items():
                results[half][stream_name][preset_name] = {}
                for lev in LEVERAGE_GRID:
                    r_lev = lever(r_arr, float(lev), rf_arr, preset.financing_markup)
                    if args.intraday_haircut != 1.0:
                        r_lev = np.where(r_lev < 0.0, r_lev * args.intraday_haircut, r_lev)

                    rng = np.random.default_rng(RNG_SEED)
                    boot_paths = block_bootstrap(
                        r_lev,
                        n_paths=BOOTSTRAP_N_PATHS,
                        horizon=HORIZON,
                        block=BOOTSTRAP_BLOCK,
                        rng=rng,
                    )
                    hist_paths = historical_paths(r_lev, horizon=HORIZON, step=HIST_STEP)

                    boot_stat = evaluate(boot_paths, preset)
                    hist_stat = evaluate(hist_paths, preset)

                    item = {
                        "stream": stream_name,
                        "preset": preset_name,
                        "leverage": lev,
                        "boot": boot_stat,
                        "hist": hist_stat,
                    }
                    results[half][stream_name][preset_name][lev] = item
                    if half == "H1":
                        h1_flat_list.append(item)
                    else:
                        h2_flat_list.append(item)

    # 5. Walk-forward selection & verdict computation
    print("[5/5] Performing walk-forward selection and verdict computation...")
    h2_summary = []
    for cand_name in candidates:
        for preset_name, _preset in PRESETS.items():
            # Pick best leverage by EV on H1 bootstrap paths
            best_lev = max(
                LEVERAGE_GRID,
                key=lambda L: results["H1"][cand_name][preset_name][L]["boot"].ev_per_attempt,
            )

            cand_h2_boot = results["H2"][cand_name][preset_name][best_lev]["boot"]
            cand_h2_hist = results["H2"][cand_name][preset_name][best_lev]["hist"]
            qqq_h2_boot = results["H2"]["QQQ"][preset_name][best_lev]["boot"]
            bma_h2_boot = results["H2"]["blend minus alpha"][preset_name][best_lev]["boot"]

            v_qqq = verdict(cand_h2_boot, qqq_h2_boot)
            v_bma = verdict(cand_h2_boot, bma_h2_boot)

            # Bookkeeping trial record
            record_trial(
                bot=f"PropSim_{cand_name.replace(' ', '_')}",
                params={"preset": preset_name, "leverage": best_lev, "half": "H2"},
                alpha=astats.alpha if (cand_name == "C2 blend" and astats) else None,
                alpha_t=astats.t if (cand_name == "C2 blend" and astats) else None,
                beta=astats.beta if (cand_name == "C2 blend" and astats) else None,
                n=cand_h2_boot.n_paths,
            )

            h2_summary.append(
                {
                    "candidate": cand_name,
                    "preset": preset_name,
                    "leverage": best_lev,
                    "cand_boot": cand_h2_boot,
                    "cand_hist": cand_h2_hist,
                    "qqq_boot": qqq_h2_boot,
                    "bma_boot": bma_h2_boot,
                    "verdict_qqq": v_qqq,
                    "verdict_zero_alpha": v_bma,
                }
            )

    # Print summary table to stdout
    print("\n" + "=" * 105)
    print("WALK-FORWARD SELECTION RESULTS (LEVERAGE CHOSEN ON H1, EVALUATED ON H2)")
    print("=" * 105)
    print(
        f"{'Candidate':<20} {'Preset':<18} {'Lev':<4} {'H2 P(Pass)':<11} {'H2 P(Brch)':<11} "
        f"{'H2 EV Boot':<11} {'H2 EV Hist':<11} {'QQQ EV':<10} {'Verdict vs QQQ':<22}"
    )
    print("-" * 105)
    for row in h2_summary:
        print(
            f"{row['candidate']:<20} {row['preset']:<18} {row['leverage']:<4} "
            f"{format_pct(row['cand_boot'].p_pass):<11} {format_pct(row['cand_boot'].p_breach):<11} "
            f"{format_usd(row['cand_boot'].ev_per_attempt):<11} {format_usd(row['cand_hist'].ev_per_attempt):<11} "
            f"{format_usd(row['qqq_boot'].ev_per_attempt):<10} {row['verdict_qqq']:<22}"
        )
    print("=" * 105)

    if args.write_doc:
        doc_content = build_markdown_doc(
            h1_results=h1_flat_list,
            h2_results=h2_flat_list,
            chosen={"h2_summary": h2_summary},
            n_obs=n_obs,
            intraday_haircut=args.intraday_haircut,
            start_date=start_date_str,
            end_date=end_date_str,
        )
        doc_path = Path("docs/backtests/prop-challenge-2026-11.md")
        doc_path.parent.mkdir(parents=True, exist_ok=True)
        doc_path.write_text(doc_content, encoding="utf-8")
        print(f"\nWrote results to {doc_path}")


if __name__ == "__main__":
    main()

def init_local_db(scratch: Path) -> None:
    """Initialize local SQLite DB for offline backtest trials."""
    db_file = scratch / "instflow_hysteresis_trials.db"
    eng = create_engine(f"sqlite:///{db_file}", connect_args={"check_same_thread": False})
    db.Base.metadata.create_all(eng)
    db.SessionLocal = sessionmaker(bind=eng, autocommit=False, autoflush=False)
    db._schema_initialized = True


def get_cache_dir() -> Path:
    scratch = os.environ.get("RETUNE_SCRATCH")
    if scratch:
        p = Path(scratch)
        p.mkdir(parents=True, exist_ok=True)
        return p
    # Reuse .cache/sp500 if present or fall back to .cache/instflow
    sp500_cache = Path(".cache/sp500")
    if sp500_cache.exists():
        return sp500_cache
    default_p = Path(".cache/instflow")
    default_p.mkdir(parents=True, exist_ok=True)
    return default_p


def download_irx_daily(start: str = FETCH_START) -> pd.Series:
    """Daily 13-week Treasury bill rate (^IRX / 100 / 252) as cash return proxy."""
    try:
        raw = yf.download("^IRX", start=start, auto_adjust=False, progress=False)
        if isinstance(raw.columns, pd.MultiIndex):
            raw.columns = raw.columns.get_level_values(0)
        c = raw["Close"].dropna()
        c.index = pd.to_datetime(c.index).tz_localize(None).normalize()
        return (c / 100.0 / 252.0).astype(float)
    except Exception as exc:
        logger.warning("Could not download ^IRX (%s); using 0.015/252 fallback", exc)
        return pd.Series()


def simulate_hysteresis(
    top_n: int,
    hold_rank: int | None,
    by_date: dict[pd.Timestamp, dict[str, Any]],
    dates: list[pd.Timestamp],
    qqq_frame: pd.DataFrame,
    start_date: str,
    end_date: str,
    rf_series: pd.Series,
    candidate_universe: set[str],
) -> dict[str, Any]:
    """
    Simulate weekly InstitutionalFlow strategy with or without turnover hysteresis.
    Tracks fills per week, turnover, and cost-adjusted returns.
    """
    if not dates:
        return {}

    current_weights: dict[str, float] = {}
    portfolio_daily_rets: list[float] = []
    portfolio_cash_shares: list[float] = []
    daily_turnover: list[float] = []
    weekly_fills: list[int] = []
    ew_daily_rets: list[float] = []
    timestamps: list[pd.Timestamp] = []

    for i in range(len(dates) - 1):
        dt = dates[i]
        next_dt = dates[i + 1]
        timestamps.append(next_dt)

        # Weekly rebalance on Friday (Mon=0, Fri=4)
        is_rebalance_bar = dt.weekday() == 4

        if is_rebalance_bar:
            # 1. Market gate (QQQ close vs inst_sma200)
            qqq_row = by_date.get(dt, {}).get(BENCHMARK)
            gate_pass = True
            if qqq_row is not None:
                close = qqq_row.get("close", np.nan)
                sma200 = qqq_row.get("inst_sma200", np.nan)
                if pd.isna(sma200) or pd.isna(close) or float(close) < float(sma200):
                    gate_pass = False

            if not gate_pass:
                target_weights: dict[str, float] = {}
                fills_this_week = 0
            else:
                rows_today = by_date.get(dt, {})
                eligible = {
                    t: rows_today[t]
                    for t in candidate_universe
                    if t in rows_today and passes_mandate(rows_today[t], min_adv_usd=50e6, min_price=10.0)
                }
                if not eligible:
                    target_weights = {}
                    fills_this_week = 0
                else:
                    scores = accumulation_score(eligible)
                    ranked = sorted(scores, key=lambda t: scores[t], reverse=True)

                    if hold_rank is None:
                        picks = ranked[:top_n]
                        fills_this_week = len(set(picks) - set(current_weights.keys()))
                    else:
                        survivors = [s for s in ranked[:hold_rank] if s in current_weights][:top_n]
                        open_slots = top_n - len(survivors)
                        survivors_set = set(survivors)
                        fills = [s for s in ranked if s not in survivors_set][:open_slots]
                        picks = survivors + fills
                        fills_this_week = len(fills)

                    target_weights = dict.fromkeys(picks, 1.0 / top_n)

            # Turnover = sum(|w_target - w_current|) / 2
            all_syms = set(current_weights.keys()) | set(target_weights.keys())
            turnover = sum(abs(target_weights.get(s, 0.0) - current_weights.get(s, 0.0)) for s in all_syms) / 2.0
            daily_turnover.append(turnover)
            weekly_fills.append(fills_this_week)
            current_weights = target_weights
        else:
            daily_turnover.append(0.0)

        # Cash share
        gross_invested = sum(current_weights.values())
        portfolio_cash_shares.append(max(0.0, 1.0 - gross_invested))

        # Return from dt to next_dt
        rows_today = by_date.get(dt, {})
        rows_next = by_date.get(next_dt, {})
        stock_ret = 0.0
        for s, w in current_weights.items():
            r1 = rows_today.get(s)
            r2 = rows_next.get(s)
            if r1 is not None and r2 is not None and r1.get("close", 0) > 0:
                ret = (r2["close"] - r1["close"]) / r1["close"]
                stock_ret += w * ret
        portfolio_daily_rets.append(stock_ret)

        # Equal-weight hold benchmark of active universe
        cand_rets = []
        for s in candidate_universe:
            r1 = rows_today.get(s)
            r2 = rows_next.get(s)
            if r1 is not None and r2 is not None and r1.get("close", 0) > 0:
                cand_rets.append((r2["close"] - r1["close"]) / r1["close"])
        ew_daily_rets.append(float(np.mean(cand_rets)) if cand_rets else 0.0)

    # Return series
    ret_series = pd.Series(portfolio_daily_rets, index=timestamps)
    cash_series = pd.Series(portfolio_cash_shares, index=timestamps)
    turnover_series = pd.Series(daily_turnover, index=timestamps)
    ew_series = pd.Series(ew_daily_rets, index=timestamps)

    # QQQ return series
    qqq_sub = qqq_frame[(qqq_frame["timestamp"] >= start_date) & (qqq_frame["timestamp"] <= end_date)].set_index(
        "timestamp"
    )["close"]
    qqq_ret = qqq_sub.pct_change().dropna().reindex(ret_series.index).fillna(0.0)

    # Risk-free rate
    rf = rf_series.reindex(ret_series.index).fillna(0.0)
    ret_tbill = ret_series + cash_series * rf

    # Cost-adjusted returns
    ret_5bp = ret_series - turnover_series * 0.0005
    ret_20bp = ret_series - turnover_series * 0.0020

    avg_fills = float(np.mean(weekly_fills)) if weekly_fills else 0.0

    return {
        "ret": ret_series,
        "ret_tbill": ret_tbill,
        "ret_5bp": ret_5bp,
        "ret_20bp": ret_20bp,
        "cash_share": cash_series,
        "turnover": turnover_series,
        "qqq_ret": qqq_ret,
        "ew_ret": ew_series,
        "avg_fills": avg_fills,
    }


def compute_metrics(
    strategy_ret: pd.Series,
    qqq_ret: pd.Series,
    ew_ret: pd.Series | None = None,
    avg_fills: float = 0.0,
) -> dict[str, float]:
    """Compute alpha vs QQQ and vs EW, t-stat, beta, Sharpe, and CAGR."""
    if len(strategy_ret) < 10:
        return {}

    stats_qqq = alpha_stats(strategy_ret, qqq_ret)
    alpha = getattr(stats_qqq, "alpha", 0.0) or 0.0
    alpha_t = getattr(stats_qqq, "t", 0.0) or 0.0
    beta = getattr(stats_qqq, "beta", 0.0) or 0.0
    corr = getattr(stats_qqq, "corr", 0.0) or 0.0

    cum = (1.0 + strategy_ret).cumprod()
    n_years = len(strategy_ret) / 252.0
    cagr = float(cum.iloc[-1] ** (1.0 / n_years) - 1.0) if n_years > 0 else 0.0
    max_dd = float((cum / cum.cummax() - 1.0).min())

    vs_ew_alpha = None
    vs_ew_t = None
    if ew_ret is not None and len(ew_ret) == len(strategy_ret):
        stats_ew = alpha_stats(strategy_ret, ew_ret)
        vs_ew_alpha = getattr(stats_ew, "alpha", None)
        vs_ew_t = getattr(stats_ew, "t", None)

    return {
        "alpha": alpha * 100.0,
        "alpha_t": alpha_t,
        "beta": beta,
        "corr": corr,
        "cagr": cagr * 100.0,
        "max_dd": max_dd * 100.0,
        "alpha_vs_ew": vs_ew_alpha * 100.0 if vs_ew_alpha is not None else None,
        "t_vs_ew": vs_ew_t,
        "avg_fills": avg_fills,
    }


def generate_markdown(
    variant_results: dict[str, dict[str, Any]],
    universe_size: int,
    dry_run: bool = False,
) -> str:
    """Generate study markdown report directly from computed numbers."""
    v1 = variant_results.get("instflow_hold_none")
    v2 = variant_results.get("instflow_hold_30")
    v3 = variant_results.get("instflow_hold_40")
    if v1 is not None and v2 is not None and v3 is not None and v1 == v2 == v3:
        raise RuntimeError("Hysteresis variants produced identical metrics; parameter had no effect.")

    doc = []
    if dry_run:
        doc.append("SYNTHETIC SMOKE TEST, NOT RESULTS\n")
    doc.extend(
        [
            "# InstitutionalFlowBot Turnover Hysteresis Study (2026-11)",
            "",
            "Evaluates whether adding rank hysteresis (`hold_rank`) to InstitutionalFlowBot reduces churn and trading costs "
            "without destroying momentum alpha.",
            "",
            "## Problem and Mechanism",
            "",
            "- **The churn problem:** In weekly cross-sectional ranking with `top_n=20`, names oscillating between ranks 18 and 22 "
            "are repeatedly bought and sold through slippage and commissions, despite their accumulation scores being statistically indistinguishable.",
            "- **Turnover hysteresis:** A holding stays as long as it still passes the mandate filter and ranks within `hold_rank`; "
            "open slots are filled from the top.",
            "- **Stateless implementation:** Computed statelessly by replaying weekly ranking over trailing 26 Fridays from `self.datas`, "
            "ensuring live CronJob execution and backtests produce identical target weights without instance state.",
            "",
            "## Study Setup",
            "",
            f"- **Universe:** S&P 100 ({universe_size} traded names) + QQQ benchmark.",
            "- **Windows:** H1 = 2019-01-01 to 2022-12-31 (parameter selection), H2 = 2023-01-01 to 2026-11-01 (unseen judgment).",
            "- **Baselines:** Dual baselines: QQQ and an equal-weight buy-and-hold of the active universe.",
            "- **Cash:** Idle cash parked at 0% and at T-bill yield (^IRX / 252, matching live copier in SHV).",
            "- **Costs:** 5 bp per side (institutional baseline) and 20 bp per side (conservative retail).",
            "- **Promotion Bar:** Must beat default (`hold_rank=None`) on H2 alpha t vs QQQ AND on 20 bp CAGR.",
            "",
            "## Pre-Registered Variants",
            "",
            "| Variant | top_n | hold_rank | Description |",
            "|---|---|---|---|",
        ]
    )

    for vname, cfg in PRE_REGISTERED_VARIANTS.items():
        doc.append(f"| {vname} | {cfg['top_n']} | {cfg['hold_rank']} | {cfg['description']} |")

    doc.append("\n## Results\n")
    doc.append("### Baseline Performance (5 bp cost)\n")
    doc.append("| Variant | hold_rank | Window | Alpha vs QQQ | Beta | Corr | MaxDD | Alpha vs EW | Fills/Week |")
    doc.append("|---|---|---|---|---|---|---|---|---|")

    for vname, vdata in variant_results.items():
        cfg = PRE_REGISTERED_VARIANTS[vname]
        for w in ["H1", "H2", "FULL"]:
            m = vdata.get(w, {})
            if not m:
                continue
            alpha_str = f"{m.get('alpha', 0):+.1f}% ({m.get('alpha_t', 0):.2f})"
            ew_str = (
                f"{m.get('alpha_vs_ew', 0):+.1f}% ({m.get('t_vs_ew', 0):.2f})"
                if m.get("alpha_vs_ew") is not None
                else "n/a"
            )
            doc.append(
                f"| {vname} | {cfg['hold_rank']} | {w} | "
                f"{alpha_str} | {m.get('beta', 0):.2f} | {m.get('corr', 0):.2f} | {m.get('max_dd', 0):.1f}% | {ew_str} | "
                f"{m.get('avg_fills', 0):.2f} |"
            )

    doc.append("\n### Cash and Cost Variations (FULL Window)\n")
    doc.append(
        "| Variant | hold_rank | CAGR (0% cash) | CAGR (T-bill) | CAGR (20 bp cost) | H1 Alpha (t) | H2 Alpha (t) | H2 Fills/Wk |"
    )
    doc.append("|---|---|---|---|---|---|---|---|")

    for vname, vdata in variant_results.items():
        cfg = PRE_REGISTERED_VARIANTS[vname]
        m_full = vdata.get("FULL", {})
        m_h1 = vdata.get("H1", {})
        m_h2 = vdata.get("H2", {})
        if not m_full:
            continue
        cagr_0 = f"{m_full.get('cagr', 0):+.1f}%"
        cagr_tbill = f"{m_full.get('cagr_tbill', 0):+.1f}%"
        cagr_20bp = f"{m_full.get('cagr_20bp', 0):+.1f}%"
        h1_str = f"{m_h1.get('alpha', 0):+.1f}% ({m_h1.get('alpha_t', 0):.2f})"
        h2_str = f"{m_h2.get('alpha', 0):+.1f}% ({m_h2.get('alpha_t', 0):.2f})"
        h2_fills = f"{m_h2.get('avg_fills', 0):.2f}"
        doc.append(
            f"| {vname} | {cfg['hold_rank']} | {cagr_0} | {cagr_tbill} | {cagr_20bp} | {h1_str} | {h2_str} | {h2_fills} |"
        )

    doc.append("\n## Verdict and Decision\n")
    doc.append("- **Bar**: New parameter ships only if winner beats default on H2 alpha t AND on 20 bp CAGR.\n")

    default_data = variant_results.get("instflow_hold_none", {})
    def_h2_t = default_data.get("H2", {}).get("alpha_t", -999.0)
    def_full_20bp = default_data.get("FULL", {}).get("cagr_20bp", -999.0)

    winner_name = None
    best_h2_t = def_h2_t

    for vname in ["instflow_hold_30", "instflow_hold_40"]:
        vdata = variant_results.get(vname, {})
        v_h2_t = vdata.get("H2", {}).get("alpha_t", -999.0)
        v_full_20bp = vdata.get("FULL", {}).get("cagr_20bp", -999.0)
        if v_h2_t > def_h2_t and v_full_20bp > def_full_20bp and v_h2_t > best_h2_t:
            best_h2_t = v_h2_t
            winner_name = vname

    if winner_name is not None:
        win_cfg = PRE_REGISTERED_VARIANTS[winner_name]
        doc.append(
            f"**Promoted Variant**: `{winner_name}` (hold_rank={win_cfg['hold_rank']}) beats the default on H2 alpha t "
            f"({best_h2_t:.2f} vs {def_h2_t:.2f}) and on 20 bp CAGR.\n"
        )
    else:
        doc.append(
            "**Outcome**: `Default stays None`.\n"
            "Neither `hold_rank=30` nor `hold_rank=40` cleared the hurdle of beating the default on both H2 alpha t "
            f"and 20 bp CAGR (default H2 t={def_h2_t:.2f}, default 20bp CAGR={def_full_20bp:.2f}%). InstitutionalFlowBot ships with default `hold_rank=None`.\n"
        )

    return "\n".join(doc) + "\n"


def run_study(dry_run: bool = False, out_path: Path = DEFAULT_DOC_OUT) -> int:
    t0 = time.time()
    if dry_run:
        out_path = Path(tempfile.gettempdir()) / out_path.name
    cache_dir = get_cache_dir()
    init_local_db(cache_dir)
    logger.info("Starting InstitutionalFlow turnover hysteresis study (dry_run=%s)", dry_run)

    # 1. Select symbols
    if dry_run:
        sample_symbols = sorted([*list(SP100)[:12], BENCHMARK])
        logger.info("Dry-run mode: testing with %d symbols", len(sample_symbols))
    else:
        sample_symbols = sorted([*list(SP100), BENCHMARK])
        logger.info("Full study mode: testing with %d symbols", len(sample_symbols))

    # 2. Load frames and compute TA features
    raw_frames = load_prices(sample_symbols, start=FETCH_START, cache_dir=cache_dir)
    if not dry_run:
        require_coverage(raw_frames, SP100, min_share=0.95, label="SP100 current universe")

    frames: dict[str, pd.DataFrame] = {}
    for s in sample_symbols:
        f = raw_frames.get(s, pd.DataFrame())
        if not f.empty and len(f) > 50:
            try:
                frames[s] = add_institutional_features(f)
            except Exception as exc:
                logger.debug("Error adding features for %s: %s", s, exc)

    logger.info("Loaded institutional TA frames for %d symbols", len(frames))
    if BENCHMARK not in frames:
        logger.error("Missing benchmark %s", BENCHMARK)
        return 1

    qqq_frame = frames[BENCHMARK]
    rf_series = download_irx_daily(start=FETCH_START)

    # 3. Pre-index frames by timestamp
    candidate_universe = {s for s in frames if s != BENCHMARK}
    dates = qqq_frame[(qqq_frame["timestamp"] >= START_DATE) & (qqq_frame["timestamp"] <= END_DATE)][
        "timestamp"
    ].tolist()
    sorted_dates = sorted(dates)

    by_date: dict[pd.Timestamp, dict[str, Any]] = {d: {} for d in sorted_dates}
    for s, f in frames.items():
        sub = f[(f["timestamp"] >= START_DATE) & (f["timestamp"] <= END_DATE)].set_index("timestamp")
        d_map = sub.to_dict("index")
        for dt, row_dict in d_map.items():
            if dt in by_date:
                by_date[dt][s] = row_dict

    # 4. Evaluate each pre-registered variant
    variant_results: dict[str, dict[str, Any]] = {}

    for vname, cfg in PRE_REGISTERED_VARIANTS.items():
        logger.info("Evaluating variant: %s (%s)", vname, cfg["description"])
        top_n = cfg["top_n"]
        hold_rank = cfg["hold_rank"]
        variant_results[vname] = {}

        for wname, (w_start, w_end) in WINDOWS.items():
            w_dates = [d for d in sorted_dates if pd.Timestamp(w_start) <= d <= pd.Timestamp(w_end)]
            sim = simulate_hysteresis(
                top_n=top_n,
                hold_rank=hold_rank,
                by_date=by_date,
                dates=w_dates,
                qqq_frame=qqq_frame,
                start_date=w_start,
                end_date=w_end,
                rf_series=rf_series,
                candidate_universe=candidate_universe,
            )
            if not sim:
                continue

            m_5bp = compute_metrics(sim["ret_5bp"], sim["qqq_ret"], sim["ew_ret"], sim["avg_fills"])
            m_tbill = compute_metrics(sim["ret_tbill"], sim["qqq_ret"], sim["ew_ret"], sim["avg_fills"])
            m_20bp = compute_metrics(sim["ret_20bp"], sim["qqq_ret"], sim["ew_ret"], sim["avg_fills"])

            res = dict(m_5bp)
            res["cagr_tbill"] = m_tbill.get("cagr", 0.0)
            res["cagr_20bp"] = m_20bp.get("cagr", 0.0)
            variant_results[vname][wname] = res

        # Record trial in registry
        full_res = variant_results[vname].get("FULL", {})
        try:
            record_trial(
                bot="InstitutionalFlowBot",
                params={"top_n": top_n, "hold_rank": hold_rank, "variant": vname},
                alpha=full_res.get("alpha"),
                alpha_t=full_res.get("alpha_t"),
                beta=full_res.get("beta"),
                n=len(full_res),
            )
        except Exception as e:
            logger.debug("Failed to record trial: %s", e)

    # 5. Generate and write markdown report
    doc_text = generate_markdown(variant_results, len(candidate_universe), dry_run=dry_run)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(doc_text)
    logger.info("Wrote study report to %s (%d bytes)", out_path, len(doc_text))

    logger.info("Completed study in %.1fs", time.time() - t0)
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="InstitutionalFlow turnover hysteresis study")
    parser.add_argument("--dry-run", action="store_true", help="Run quick dry-run with subset of symbols")
    parser.add_argument("--out", type=Path, default=DEFAULT_DOC_OUT, help="Output markdown path")
    args = parser.parse_args()

    return run_study(dry_run=args.dry_run, out_path=args.out)


if __name__ == "__main__":
    sys.exit(main())

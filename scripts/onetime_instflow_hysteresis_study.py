"""Walk-forward study: InstitutionalFlowBot turnover hysteresis (PLAN-alphaideas.md step C1).

Evaluates whether turnover hysteresis (buffer zone) reduces churn and transaction costs
without sacrificing alpha. In weekly momentum ranking, names near the rank cutoff churn
frequently between ranks 18-22, generating unnecessary turnover and execution drag.
Under hysteresis, a holding stays as long as it still passes the mandate filter and ranks
within `hold_rank`; open slots fill from the top.

Pre-registered variants (3 combinations <= 12 limit):
  1. instflow_hold_none : SP100 baseline, top_n=20, hold_rank=None (shipped default, no hysteresis)
  2. instflow_hold_30   : SP100, top_n=20, hold_rank=30 (ranks 1-30 keep held names, open slots fill from top)
  3. instflow_hold_40   : SP100, top_n=20, hold_rank=40 (ranks 1-40 keep held names, open slots fill from top)

Decision rule (PLAN-alphaideas.md):
  - Judge H2 on alpha t vs QQQ and vs EW, fills per week, CAGR at 20 bp cost.
  - Default stays `None` unless the winner beats it on H2 alpha t AND on 20 bp CAGR.

Rules and constraints:
  - Dual baselines: QQQ and equal-weight buy-and-hold of the active S&P 100 universe.
  - Cash yield: reported at 0% (paper metric) and T-bill yield (^IRX / 252, SHV copier metric).
  - Transaction costs: 5 bp per side (institutional) and 20 bp per side (conservative retail).
  - Walk-forward splits: H1 (2019-01-01 .. 2022-12-31), H2 (2023-01-01 .. 2026-11-01), FULL.
  - Pre-registered: all variants recorded in `tradingbot/utils/trial_registry.py`.
  - No hand-written findings: all numbers and markdown tables generated by this script.

Usage:
    PYTHONPATH=. uv run python scripts/onetime_instflow_hysteresis_study.py [--dry-run] [--out DOC_PATH]
"""


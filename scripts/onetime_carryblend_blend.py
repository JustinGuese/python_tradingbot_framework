"""S5 (reduced): do SignedFxCarryBot and FxMomentumLSBot add anything as a pair? (PLAN-carryblend.md).

Stream level only. The five SleeveBlend streams cannot be rebuilt here (the event-book caches under
/tmp are gone), so no integration into SleeveBlendBot is attempted. Inverse-vol weights are fit on H1
only; H2 is the judgement. Real data, same loaders and cost model as onetime_carryblend_tune.py.

Usage: POSTGRES_URI=x:y@127.0.0.1:1/z uv run python scripts/onetime_carryblend_blend.py
Writes docs/backtests/carryblend-blend-2026-11.md
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import onetime_carryblend_tune as t

OUT = Path("docs/backtests/carryblend-blend-2026-11.md")


def main() -> None:
    frames = t.load_frames([*t.ALL_FX_PAIRS, *t.FX_ETFS, "QQQ", "^IRX"])
    qqq_close = frames["QQQ"]["close"].set_axis(pd.DatetimeIndex(frames["QQQ"]["timestamp"]))
    q = qqq_close.pct_change().dropna()
    rf = (frames["^IRX"]["close"].set_axis(pd.DatetimeIndex(frames["^IRX"]["timestamp"])) / 100 / 252).dropna()
    carry = t.run_cell(
        t.SignedFxCarryBot, {"k": 3, "gross": 1.0, "markup": 0.0}, frames, qqq_close, list(t.ALL_FX_PAIRS)
    )
    mom = t.run_cell(t.FxMomentumLSBot, {"window": 189, "k": 3, "gross": 1.0}, frames, qqq_close, list(t.FX_ETFS))
    mom = mom + rf.reindex(mom.index).fillna(0.0)  # parity basis, as in the tuning doc
    df = pd.DataFrame({"SignedFxCarry": carry, "FxMomentumLS": mom}).dropna()
    df = df[(df.index >= t.EVAL_START) & (df.index.dayofweek < 5)]
    qq = q.reindex(df.index)
    mid = len(df) // 2
    vol_h1 = df.iloc[:mid].std()
    w = (1 / vol_h1) / (1 / vol_h1).sum()
    streams = {**{c: df[c] for c in df}, "H1 inverse-vol blend": (df * w).sum(axis=1), "50/50 blend": df.mean(axis=1)}
    lines = ["# Carry + momentum pair, stream level (2026-11)", ""]
    lines += [
        "Generated by `scripts/onetime_carryblend_blend.py`. Not integrated into SleeveBlendBot: its five streams need",
        "event-book caches that no longer exist, so this tests only whether the two new FX streams add to each other.",
        f"Weights fit on H1 only: SignedFxCarry {w['SignedFxCarry']:.2f}, FxMomentumLS {w['FxMomentumLS']:.2f}.",
        f"Correlation of daily returns, SignedFxCarry vs FxMomentumLS: {df.corr().iloc[0, 1]:+.2f}; "
        f"vs QQQ: carry {df['SignedFxCarry'].corr(qq):+.2f}, momentum {df['FxMomentumLS'].corr(qq):+.2f}.",
        "",
        "| stream | full alpha (t) | H1 alpha (t) | H2 alpha (t) | beta | max DD |",
        "|---|---|---|---|---|---|",
    ]
    h2t = {}
    for name, r in streams.items():
        s = t.stats_row(r, q)
        h2t[name] = s["h2"]["t"]
        lines.append(
            f"| {name} | {t.fmt(s['full'])} | {t.fmt(s['h1'])} | {t.fmt(s['h2'])} | {s['full']['beta']:+.2f} | "
            f"{s['maxdd'] * 100:.1f}% |"
        )
    best_single = max(h2t["SignedFxCarry"], h2t["FxMomentumLS"])
    adds = h2t["H1 inverse-vol blend"] > best_single
    lines += [
        "",
        f"Computed verdict: blend H2 t {h2t['H1 inverse-vol blend']:+.2f} vs best single stream {best_single:+.2f} -> "
        f"{'the pair improves on its best member' if adds else 'the pair does not improve on its best member'}.",
        "Contango overlay on the equity sleeves: NOT RUN (equity sleeve streams are not rebuildable here).",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines), file=sys.stderr)


if __name__ == "__main__":
    main()

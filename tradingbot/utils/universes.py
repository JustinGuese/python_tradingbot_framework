_SP500_CHANGES: list[tuple[str, str, str]] | None = None


def _load_sp500_changes() -> list[tuple[str, str, str]]:
    global _SP500_CHANGES
    if _SP500_CHANGES is not None:
        return _SP500_CHANGES

    changes_path = Path(__file__).resolve().parents[2] / "data" / "sp500_changes.csv"
    if not changes_path.is_file():
        _SP500_CHANGES = []
        return _SP500_CHANGES

    rows: list[tuple[str, str, str]] = []
    with open(changes_path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for r in reader:
            d = r.get("date", "").strip()
            a = r.get("added", "").strip()
            rem = r.get("removed", "").strip()
            if d and (a or rem):
                rows.append((d, a, rem))

    # Reverse-chronological order (newest date first)
    rows.sort(key=lambda x: x[0], reverse=True)
    _SP500_CHANGES = rows
    return _SP500_CHANGES


def _normalize_as_of(as_of: Any) -> str:
    if isinstance(as_of, (date, datetime)):
        return as_of.strftime("%Y-%m-%d")
    if hasattr(as_of, "strftime"):
        return as_of.strftime("%Y-%m-%d")
    s = str(as_of).strip()
    if len(s) == 4 and s.isdigit():
        return f"{s}-12-31"
    if len(s) == 7 and s[4] == "-":
        import pandas as pd

        return pd.Period(s, "M").end_time.strftime("%Y-%m-%d")
    try:
        import pandas as pd

        return pd.to_datetime(s).strftime("%Y-%m-%d")
    except Exception:
        return s


@functools.lru_cache(maxsize=1024)
def _sp500_members_cached(as_of_str: str) -> tuple[str, ...]:
    members = set(SP500)
    for change_date, added, removed in _load_sp500_changes():
        if change_date > as_of_str:
            if added:
                members.discard(added)
            if removed:
                members.add(removed)
    return tuple(sorted(members))


def sp500_members(as_of: Any) -> tuple[str, ...]:
    """Rebuild the S&P 500 constituents as of a given date by reversing changes

    from the current SP500 universe using data/sp500_changes.csv.
    """
    as_of_str = _normalize_as_of(as_of)
    return _sp500_members_cached(as_of_str)
